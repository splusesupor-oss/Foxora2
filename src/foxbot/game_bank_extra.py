def make_maemma_extra(limit: int = 122) -> tuple[tuple[str, tuple[str, ...]], ...]:
    records: list[tuple[str, tuple[str, ...]]] = []
    for start in range(2, 16):
        for add in range(1, 6):
            for subtract in range(1, 4):
                result = start * 2 + add - subtract
                prompt = (
                    f"معمای حسابی: عدد {_fa(start)} را دو برابر کن، بعد {_fa(add)} را اضافه "
                    f"و {_fa(subtract)} را کم کن؛ چه عددی می‌ماند؟"
                )
                answer = str(result)
                aliases = [
                    answer,
                    answer.translate(_PERSIAN_DIGITS),
                    answer.translate(_ARABIC_INDIC_DIGITS),
                ]
                if len(records) < 105:
                    aliases.append(_PERSIAN_NUMBER_WORDS[result])
                records.append((prompt, tuple(aliases)))
                if len(records) == limit:
                    return tuple(records)
    raise RuntimeError("not enough independent arithmetic puzzles")


MAEMMA_EXTRA_PARITY = make_maemma_extra()
