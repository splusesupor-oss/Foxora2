def normalized(value: str) -> str:
    text = str(value or "").strip().lower()
    for source, target in (("ي", "ی"), ("ك", "ک"), ("ۀ", "ه"), ("ة", "ه"), ("ؤ", "و"), ("أ", "ا"), ("إ", "ا"), ("آ", "ا")):
        text = text.replace(source, target)
    text = text.replace("‌", " ")
    return "".join(text.split())


def playable_rounds() -> tuple[tuple[str, str, tuple[str, ...]], ...]:
    """Return unique letter/category combinations and accepted local answers."""
    rounds: list[tuple[str, str, tuple[str, ...]]] = []
    for category, words in WHO_KNOWS_BANK.items():
        by_letter: dict[str, list[str]] = {}
        for word in words:
            key = normalized(word)
            if len(key) < 2:
                continue
            by_letter.setdefault(key[0], []).append(word)
        for letter, candidates in by_letter.items():
            accepted = tuple(dict.fromkeys(candidates))
            rounds.append((letter, category, accepted))
    return tuple(rounds)
