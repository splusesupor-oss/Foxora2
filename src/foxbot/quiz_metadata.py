def _fold(text: str) -> str:
    return unicodedata.normalize("NFKC", text).replace("\u200c", " ").casefold()


def metadata_for_question(question: str) -> tuple[str, str]:
    """Return local topic and difficulty labels without source-bank data."""
    folded = _fold(question)
    category = next(
        (
            label
            for label, markers in _CATEGORY_RULES
            if any(marker in folded for marker in markers)
        ),
        "دانش عمومی",
    )
    level = (
        "چالشی"
        if len(folded) >= 65
        or any(marker in folded for marker in _COMPLEXITY_MARKERS)
        or any(character.isdigit() for character in folded)
        else "پایه"
    )
    return category, level
